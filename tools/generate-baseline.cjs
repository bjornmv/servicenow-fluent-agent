'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const agentPath = 'payload/.copilot/agents/ServiceNow Fluent.agent.md';
const baselinePath = 'payload/.agents/instructions/now-sdk-baseline.instructions.md';
const sections = ['SDK and REST Commands', 'Terminal Discipline', 'Quiet Update Advisory', 'Documentation Lookup', 'Authoring Defaults', 'Flow and Action Guardrail', 'Build, Install, Verify'];
function renderBaseline(agent) {
  const blocks = new Map([...agent.matchAll(/^## ([^\r\n]+)\r?\n([\s\S]*?)(?=^## |$(?![\s\S]))/gm)].map(m => [m[1], m[2].trim()]));
  const selected = sections.map(name => {
    if (!blocks.has(name)) throw new Error(`Missing canonical section: ${name}`);
    return `## ${name}\n\n${blocks.get(name)}`;
  }).join('\n\n').replaceAll('../../.agents/reference/', '../reference/');
  return `---\napplyTo: "**/now.config.json,**/aiux.json,**/*.now.ts,**/metadata/**/*.xml"\ndescription: "Minimal ServiceNow safety baseline for non-agent chats; generated from the custom agent."\n---\n# ServiceNow baseline (generated)\n\n<!-- Generated by tools/generate-baseline.cjs from ${agentPath}; do not edit. -->\nOnly high-risk defaults are repeated here. The custom agent owns task routing; task-matched skills and file instructions own detailed recipes. For actual Lux/AIUX use sn-lux/sn-lux-build; for React use sn-react-ui-design/sn-ui-page-vite.\n\n${selected}\n`;
}
function generate(sourceRoot = root, check = false) {
  const expected = renderBaseline(fs.readFileSync(path.join(sourceRoot, agentPath), 'utf8'));
  const target = path.join(sourceRoot, baselinePath);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) throw new Error('Generated baseline is stale; run node tools/generate-baseline.cjs');
  } else fs.writeFileSync(target, expected);
  return expected;
}
module.exports = { generate, renderBaseline, sections, agentPath, baselinePath };
if (require.main === module) {
  try { generate(root, process.argv.includes('--check')); console.log('Instruction baseline is current.'); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
